//! docs/mcp-tools.md, generated from the MCP tools' own definitions (their
//! descriptions and input schemas), so the page says what an agent's
//! `tools/list` says (#689). The test fails when the page differs; to
//! rewrite it:
//!
//! ```sh
//! UPDATE_REFERENCE=1 cargo test -p ganymede-server --lib mcp::reference
//! ```
//!
//! Only the part between the markers is generated. A tool or parameter that
//! the latest release doesn't have gets its `**Unreleased.**` note (see
//! CLAUDE.md) above the start marker, naming it.

use serde_json::{Map, Value};

const START: &str =
    "<!-- mcp-tools:start (generated by crates/ganymede-server/src/mcp/reference.rs) -->";
const END: &str = "<!-- mcp-tools:end -->";

/// Table cell text: one line, with `|` escaped.
fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// Paragraphs as the doc comment wrote them, joined into lines.
fn prose(text: &str) -> String {
    text.split("\n\n")
        .map(|p| p.split_whitespace().collect::<Vec<_>>().join(" "))
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// A schema's type as the docs show it: `string`, `array of string`, or
/// an enum's values.
fn type_of(schema: &Value, defs: &Map<String, Value>) -> String {
    if let Some(r) = schema.get("$ref").and_then(Value::as_str) {
        let name = r.trim_start_matches("#/$defs/");
        return defs
            .get(name)
            .map(|d| type_of(d, defs))
            .unwrap_or_else(|| name.to_string());
    }
    if let Some(any) = schema.get("anyOf").and_then(Value::as_array) {
        let types: Vec<_> = any
            .iter()
            .filter(|s| s.get("type").and_then(Value::as_str) != Some("null"))
            .map(|s| type_of(s, defs))
            .collect();
        return types.join(" or ");
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return values
            .iter()
            .map(|v| format!("`{}`", v.as_str().unwrap_or_default()))
            .collect::<Vec<_>>()
            .join(", ");
    }
    if let Some(one) = schema.get("oneOf").and_then(Value::as_array) {
        return one
            .iter()
            .map(|s| {
                let c = s.get("const").and_then(Value::as_str).unwrap_or_default();
                match s.get("description").and_then(Value::as_str) {
                    Some(d) => format!(
                        "`{c}` ({})",
                        d.split_whitespace()
                            .collect::<Vec<_>>()
                            .join(" ")
                            .trim_end_matches('.')
                    ),
                    None => format!("`{c}`"),
                }
            })
            .collect::<Vec<_>>()
            .join(", ");
    }
    let ty = match schema.get("type") {
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(ts)) => ts
            .iter()
            .filter_map(Value::as_str)
            .filter(|t| *t != "null")
            .collect::<Vec<_>>()
            .join(" or "),
        _ => "any".into(),
    };
    if ty == "array" {
        if let Some(items) = schema.get("items") {
            return format!("array of {}", type_of(items, defs));
        }
    }
    ty
}

/// The page body: one section per tool, by name.
fn page() -> String {
    let mut tools = super::Notebooks::tool_router().list_all();
    tools.sort_by(|a, b| a.name.cmp(&b.name));
    let mut out = String::new();
    for tool in tools {
        out.push_str(&format!("\n## `{}`\n\n", tool.name));
        if let Some(d) = &tool.description {
            out.push_str(&format!("{}\n", prose(d)));
        }
        let schema = Value::Object((*tool.input_schema).clone());
        let empty = Map::new();
        let defs = schema
            .get("$defs")
            .and_then(Value::as_object)
            .unwrap_or(&empty);
        let required: Vec<&str> = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let Some(props) = schema
            .get("properties")
            .and_then(Value::as_object)
            .filter(|p| !p.is_empty())
        else {
            out.push_str("\nNo parameters.\n");
            continue;
        };
        out.push_str("\n| Parameter | Type | Description |\n| --- | --- | --- |\n");
        for (name, prop) in props {
            let desc = prop
                .get("description")
                .and_then(Value::as_str)
                .map(cell)
                .unwrap_or_default();
            // The page shows what `tools/list` shows, so a parameter needs
            // a doc comment on its field.
            assert!(
                !desc.is_empty(),
                "{}.{name} has no doc comment in mcp.rs",
                tool.name
            );
            let name = if required.contains(&name.as_str()) {
                format!("`{name}` (required)")
            } else {
                format!("`{name}`")
            };
            out.push_str(&format!(
                "| {name} | {} | {desc} |\n",
                cell(&type_of(prop, defs))
            ));
        }
    }
    format!("{START}\n{out}\n{END}")
}

#[test]
fn mcp_tools_page_matches_the_tools() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/mcp-tools.md");
    let doc = std::fs::read_to_string(path).unwrap();
    let (start, end) = (
        doc.find(START).expect("start marker"),
        doc.find(END).expect("end marker"),
    );
    let current = &doc[start..end + END.len()];
    let generated = page();
    if current != generated {
        if std::env::var_os("UPDATE_REFERENCE").is_some() {
            std::fs::write(path, doc.replace(current, &generated)).unwrap();
            return;
        }
        panic!(
            "docs/mcp-tools.md differs from the MCP tools. Rewrite it with\n  \
             UPDATE_REFERENCE=1 cargo test -p ganymede-server --lib mcp::reference"
        );
    }
}
